package koncurrent.internal

/**
 * What heads a bin of a [Table].
 */
internal sealed interface Bin<K : Any, V : Any>

/**
 * Heads a bin whose mappings moved to [nextTable] during a resize.
 */
internal class ForwardingNode<K : Any, V : Any>(val nextTable: Table<K, V>) : Bin<K, V>

/**
 * Reserves an empty bin while `computeIfAbsent` or `compute` establishes its mapping.
 */
internal class ReservationNode<K : Any, V : Any> : Bin<K, V>

@file:OptIn(ExperimentalForeignApi::class)

package koncurrent.internal

import kotlinx.cinterop.CFunction
import kotlinx.cinterop.COpaquePointer
import kotlinx.cinterop.CPointer
import kotlinx.cinterop.ExperimentalForeignApi
import kotlinx.cinterop.alloc
import kotlinx.cinterop.memScoped
import kotlinx.cinterop.ptr
import kotlinx.cinterop.value
import platform.posix.pthread_create
import platform.posix.pthread_detach
import platform.posix.pthread_tVar

internal actual fun createDetachedThread(
    routine: CPointer<CFunction<(COpaquePointer?) -> COpaquePointer?>>,
    argument: COpaquePointer,
): Boolean = memScoped {
    val thread = alloc<pthread_tVar>()

    pthread_create(thread.ptr, null, routine, argument) == 0 && pthread_detach(thread.value) == 0
}

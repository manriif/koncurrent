@file:OptIn(ExperimentalForeignApi::class)
@file:Suppress("NOTHING_TO_INLINE")

package koncurrent.benchmarks

import kotlinx.cinterop.ExperimentalForeignApi
import kotlinx.cinterop.alloc
import kotlinx.cinterop.nativeHeap
import kotlinx.cinterop.ptr
import platform.posix.pthread_mutex_init
import platform.posix.pthread_mutex_lock
import platform.posix.pthread_mutex_t
import platform.posix.pthread_mutex_unlock

internal actual class PthreadMutex {

    // Not private, for the inline functions
    val mutex = nativeHeap.alloc<pthread_mutex_t>()

    init {
        check(pthread_mutex_init(mutex.ptr, null) == 0)
    }

    actual inline fun lock() {
        check(pthread_mutex_lock(mutex.ptr) == 0)
    }

    actual inline fun unlock() {
        check(pthread_mutex_unlock(mutex.ptr) == 0)
    }
}
